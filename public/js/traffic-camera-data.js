/**
 * Normaliza URLs para garantir HTTPS e evitar Mixed Content
 */
export function normalizeEmbedUrl(url) {
    if (!url) return '';
    let cleanUrl = String(url).trim();
    if (cleanUrl.startsWith('http://cameras.cetsp.com.br')) {
        cleanUrl = cleanUrl.replace('http://', 'https://');
    }
    return cleanUrl;
}

/**
 * Função utilitária para contagem de métricas do catálogo CIM
 */
export function getCatalogStats() {
    let totalSources = 0;
    let onlineCount = 0;
    let externalCount = 0;
    let citiesCount = Object.keys(trafficCameraSources).length;

    Object.values(trafficCameraSources).forEach(reg => {
        if (Array.isArray(reg.sources)) {
            totalSources += reg.sources.length;
            reg.sources.forEach(src => {
                if (src.healthStatus === 'online' || src.suportaIframe || src.tipoFonte === 'snapshot') {
                    onlineCount++;
                } else {
                    externalCount++;
                }
            });
        }
    });

    return {
        totalSources,
        onlineCount,
        externalCount,
        citiesCount
    };
}

/**
 * Retorna exclusivamente as Outras Fontes do RJ que estão ativas, validadas e funcionais
 */
export function getRjAlternativeSources() {
    const allRj = trafficCameraSources.RJ?.sources || [];
    return allRj.filter(src =>
        src.providerCategory === 'OUTRAS_FONTES' &&
        src.ativa !== false &&
        src.healthStatus === 'online' &&
        (src.suportaIframe === true || src.tipoFonte === 'snapshot')
    );
}

/**
 * Retorna os destaques da base CamerasRJ (preservada para quando houver liberação pelo COR-Rio)
 */
export function getRjCamerasRjSources() {
    const allRj = trafficCameraSources.RJ?.sources || [];
    return allRj.filter(src => src.providerCategory === 'CAMERAS_RJ' || src.sourceProvider === 'CamerasRJ');
}

/**
 * Retorna as câmeras georreferenciadas de uma Regional específica (RJ, SP, MG/BH, DF/BSB, PE/REC)
 */
export function getRegionalGeoreferencedSources(regional = 'RJ') {
    const aliasMap = { 'MG': 'BH', 'DF': 'BSB', 'PE': 'REC' };
    const key = aliasMap[regional] || regional || 'RJ';
    if (key === 'RJ') {
        return getRjAlternativeSources();
    }
    const sources = trafficCameraSources[key]?.sources || [];
    return sources.filter(src => !isNaN(parseFloat(src.latitude)) && !isNaN(parseFloat(src.longitude)));
}
